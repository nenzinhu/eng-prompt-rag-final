begin;

-- 1. glossario_termos — existe no projeto vivo, mas faltava no recriar-banco.sql.
--    termo_normalizado é coluna GERADA (confirmado no servidor: erro 428C9) e é
--    o alvo do on_conflict que o backend usa.
create table if not exists public.glossario_termos (
  id               bigint generated by default as identity primary key,
  termo            text not null,
  termo_normalizado text generated always as (lower(termo)) stored,
  explicacao       text not null,
  exemplo          text,
  origem           text,
  created_at       timestamptz not null default now()
);

create unique index if not exists glossario_termos_termo_normalizado_key
  on public.glossario_termos (termo_normalizado);

-- 2. Índice vetorial. Sem ele, match_ementas faz varredura completa e calcula
--    a distância de todas as linhas a cada pergunta.
create index if not exists ementas_chunks_embedding_hnsw
  on public.ementas_chunks using hnsw (embedding vector_cosine_ops);

-- 3. search_path explícito na função de busca. O schema da extensão vector é
--    lido do catálogo em vez de chutado — 'extensions' é o padrão do Supabase,
--    mas se estiver em outro lugar, o ALTER usaria o schema errado e quebraria
--    a busca. Erros aqui não abortam a migração (só avisam).
do $$
declare
  schema_vetor text;
begin
  select n.nspname into schema_vetor
    from pg_extension e join pg_namespace n on n.oid = e.extnamespace
   where e.extname = 'vector';

  if schema_vetor is null then
    raise notice 'Extensão vector não encontrada — pulei o ajuste de search_path.';
  else
    execute format(
      'alter function public.match_ementas(vector, integer) set search_path = public, %I',
      schema_vetor
    );
    raise notice 'search_path de match_ementas ajustado para: public, %', schema_vetor;
  end if;
exception when others then
  raise notice 'Não foi possível ajustar o search_path (%): %', sqlerrm, sqlstate;
end $$;

-- 4. RLS. A leitura continua pública (o site é um material de estudo); a
--    escrita passa a ser exclusiva da service_role, que ignora RLS por design.
alter table public.ementas_chunks   enable row level security;
alter table public.glossario_termos enable row level security;

-- 4a. Remove QUALQUER política existente nas duas tabelas. Só ligar o RLS não
--     basta se houver uma política permissiva antiga (ex.: "allow all").
do $$
declare
  p record;
begin
  for p in
    select schemaname, tablename, policyname
      from pg_policies
     where schemaname = 'public'
       and tablename in ('ementas_chunks', 'glossario_termos')
  loop
    execute format('drop policy if exists %I on %I.%I', p.policyname, p.schemaname, p.tablename);
    raise notice 'Política removida: %.% -> %', p.schemaname, p.tablename, p.policyname;
  end loop;
end $$;

-- 4b. Leitura pública, escrita nenhuma.
drop policy if exists "leitura publica chunks" on public.ementas_chunks;
create policy "leitura publica chunks"
  on public.ementas_chunks
  for select
  to anon, authenticated
  using (true);

drop policy if exists "leitura publica glossario" on public.glossario_termos;
create policy "leitura publica glossario"
  on public.glossario_termos
  for select
  to anon, authenticated
  using (true);

-- 5. Storage: o bucket 'ementas' é privado e passa a ser acessado apenas pela
--    service_role (o backend baixa/sobe os documentos no servidor). Nenhuma
--    política é criada para anon — de propósito.
--    ATENÇÃO: o backend usa a service_role para o Storage (função _h_documentos).

commit;

