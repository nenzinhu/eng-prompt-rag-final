-- 1. Extensão pgvector
create extension if not exists vector;

-- 2. Tabela dos chunks vetorizados
create table if not exists public.ementas_chunks (
  id         bigint generated by default as identity primary key,
  content    text not null,
  embedding  vector(384),          -- gte-small (Supabase Edge Runtime)
  source     text not null,
  page       integer,
  created_at timestamptz not null default now()
);

-- 3. Índice opcional para acelerar a busca por similaridade
--    (HNSW; ajuste conforme o volume)
-- create index on public.ementas_chunks
--   using hnsw (embedding vector_cosine_ops);

-- 4. Função de busca semântica usada pelo backend (api/index.py)
create or replace function public.match_ementas(
  query_embedding vector,
  match_count integer default 6
)
returns table (
  id bigint,
  content text,
  source text,
  page integer,
  similarity double precision
)
language sql
stable
as $function$
  select
    id,
    content,
    source,
    page,
    1 - (embedding <=> query_embedding) as similarity
  from ementas_chunks
  order by embedding <=> query_embedding
  limit match_count;
$function$;

