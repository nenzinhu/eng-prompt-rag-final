-- 1. Extensão pgvector
create extension if not exists vector;

-- 2. Tabela dos chunks vetorizados
create table if not exists public.ementas_chunks (
  id         bigint generated by default as identity primary key,
  content    text not null,
  embedding  vector(384),          -- gte-small (Supabase Edge Runtime) — reserva da busca
  embedding_mistral vector(1024),  -- mistral-embed (migração 2026-09-21)
  source     text not null,
  page       integer,
  created_at timestamptz not null default now()
);

-- 3. Índice para acelerar a busca por similaridade
create index if not exists ementas_chunks_embedding_hnsw
  on public.ementas_chunks using hnsw (embedding vector_cosine_ops);

create index if not exists ementas_chunks_embedding_mistral_hnsw
  on public.ementas_chunks using hnsw (embedding_mistral vector_cosine_ops);

-- 4a. Busca pelo mistral-embed: rode também o corpo de
--     migracoes/2026-09-19-busca-hibrida.sql e 2026-09-21-embedding-mistral.sql
--     (fts, match_ementas_hibrido, match_ementas_mistral, match_ementas_hibrido_mistral).

-- 4. Função de busca semântica usada pelo backend (api/index.py)
create or replace function public.match_ementas(
  query_embedding vector,
  match_count integer default 6
)
returns table (
  id bigint,
  content text,
  source text,
  page integer,
  similarity double precision
)
language sql
stable
as $function$
  select
    id,
    content,
    source,
    page,
    1 - (embedding <=> query_embedding) as similarity
  from ementas_chunks
  order by embedding <=> query_embedding
  limit match_count;
$function$;

-- search_path explícito (o schema da extensão vector é lido do catálogo).
do $$
declare
  schema_vetor text;
begin
  select n.nspname into schema_vetor
    from pg_extension e join pg_namespace n on n.oid = e.extnamespace
   where e.extname = 'vector';
  if schema_vetor is not null then
    execute format(
      'alter function public.match_ementas(vector, integer) set search_path = public, %I',
      schema_vetor
    );
  end if;
end $$;

-- 5. Glossário. `termo_normalizado` é coluna GERADA — é o alvo do on_conflict
--    usado por salvar_termos_glossario (api/index.py). Sem esta tabela, gerar
--    glossário quebra na gravação.
create table if not exists public.glossario_termos (
  id                bigint generated by default as identity primary key,
  termo             text not null,
  termo_normalizado text generated always as (lower(termo)) stored,
  explicacao        text not null,
  exemplo           text,
  origem            text,
  created_at        timestamptz not null default now()
);

create unique index if not exists glossario_termos_termo_normalizado_key
  on public.glossario_termos (termo_normalizado);

-- 6. RLS: leitura pública, escrita apenas pela service_role (que ignora RLS).
alter table public.ementas_chunks   enable row level security;
alter table public.glossario_termos enable row level security;

drop policy if exists "leitura publica chunks" on public.ementas_chunks;
create policy "leitura publica chunks"
  on public.ementas_chunks for select to anon, authenticated using (true);

drop policy if exists "leitura publica glossario" on public.glossario_termos;
create policy "leitura publica glossario"
  on public.glossario_termos for select to anon, authenticated using (true);

